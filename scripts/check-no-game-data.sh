#!/bin/bash
# Fails if anything that looks like game data is in the repository or in a
# release archive. The repository is public: no assets, no audio, no images
# made from the original's art, no decompiled code, no extracted tables, no
# replays, no game files (see CLAUDE.md, "Nothing from the game goes into git").
#
# Usage:
#   scripts/check-no-game-data.sh                  tracked files (git ls-files;
#                                                  outside a git checkout: the
#                                                  tree minus the /dirs/ that
#                                                  .gitignore lists)
#   scripts/check-no-game-data.sh --worktree       the tree minus .gitignore'd
#                                                  top-level dirs, even in git
#   scripts/check-no-game-data.sh --archives A...  release archives (.tar.gz/.zip)
#
# Rules, by file name and by content (magic bytes), for every file:
#   - images (PNG, JPEG, GIF, BMP, WebP, TGA, DDS, KTX, PSD), audio (Ogg,
#     WAV, MP3, FLAC, FSB, FMOD banks), Unity files (UnityFS bundles,
#     SerializedFiles, .assets/.resS/.resource, globalgamemanagers, level<N>,
#     sharedassets), .NET assemblies and C# sources (decompiled code), Bopl
#     replays (.rep): always rejected;
#   - any other file over 256 KB: rejected unless allowlisted below with the
#     reason it is ours / permissively licensed;
#   - executables and shared libraries only inside archives, by exact name.
set -euo pipefail
source "$(dirname "$0")/../env.sh"
cd "$BOPL_ROOT"
MODE=tracked
case "${1:-}" in
    --worktree) MODE=worktree; shift ;;
    --archives) MODE=archives; shift ;;
    "") ;;
    *) echo "usage: $0 [--worktree | --archives FILE...]" >&2; exit 2 ;;
esac
if [ $MODE = tracked ] && ! { command -v git >/dev/null && git rev-parse --is-inside-work-tree >/dev/null 2>&1; }; then
    MODE=worktree
fi
if [ $MODE = tracked ]; then
    LIST=$(mktemp)
    trap 'rm -f "$LIST"' EXIT
    git ls-files -z --cached > "$LIST"
    set -- "$LIST"
fi
python3 -I - "$MODE" "$@" <<'PY'
import fnmatch, io, os, re, sys, tarfile, zipfile

mode, args = sys.argv[1], sys.argv[2:]
LIMIT = 256 * 1024

# Large files that are ours or permissively licensed (path globs; the reason
# goes into THIRD_PARTY_NOTICES.md where it is third-party).
ALLOW_LARGE = {
    "Cargo.lock": "dependency lock file",
    "*/Cargo.lock": "dependency lock file",
    "crates/render/assets/fonts/NotoSans-Bold.ttf": "Noto Sans, SIL OFL 1.1 (dev overlay font)",
    "crates/unity/data/fsb5_vorbis_setup.bin": "libvorbis setup headers via fsbex (MIT/Apache-2.0)",
    "crates/unity/typetrees/*.json": "field layouts (names/types) for the reader, generated by scripts/dev/gen_typetrees.py; no asset data",
    "docs/spec/*.md": "our clean-room behaviour specs (text)",
    "docs/*.md": "documentation (text)",
    "licenses/RUST_DEPENDENCIES.txt": "generated license texts of the Rust crates",
}
# Binaries that belong in release archives (path below the top-level folder).
ARCHIVE_BINARIES = {"bopl-port", "bopl-port.exe", "SDL2.dll", "lib/libSDL2-2.0.so.0"}

BAD_EXT = re.compile(
    r"\.(png|jpe?g|gif|bmp|webp|tga|dds|ktx2?|psd|exr|hdr|ico|"
    r"ogg|oga|wav|mp3|flac|aiff?|fsb|bank|"
    r"assets|ress|resource|bundle|unity3d|unity|prefab|asset|"
    r"dll|exe|so|dylib|pdb|cs|il|rep)$", re.I)
BAD_NAME = re.compile(
    r"(^|/)(globalgamemanagers|level\d+|sharedassets\d+|resources\.assets|"
    r"Assembly-CSharp[^/]*|BoplBattle[^/]*|UnityPlayer[^/]*)$", re.I)
MAGIC = [
    (b"\x89PNG\r\n\x1a\n", "PNG image"),
    (b"\xff\xd8\xff", "JPEG image"),
    (b"GIF8", "GIF image"),
    (b"OggS", "Ogg audio"),
    (b"fLaC", "FLAC audio"),
    (b"ID3", "MP3 audio"),
    (b"FSB5", "FMOD sound bank"),
    (b"UnityFS", "Unity bundle"),
    (b"UnityWeb", "Unity bundle"),
    (b"UnityRaw", "Unity bundle"),
    (b"DDS ", "DDS texture"),
    (b"\xabKTX", "KTX texture"),
    (b"8BPS", "Photoshop image"),
]
# (character classes so that this script does not match itself)
DECOMPILED = re.compile(rb"ICSharpCode[.]Decompiler|// Decompiled[ ]with|^using UnityEngine[;]", re.M)

def sniff(head):
    for m, what in MAGIC:
        if head.startswith(m):
            return what
    if head[:4] == b"RIFF" and head[8:12] in (b"WAVE", b"WEBP"):
        return "RIFF " + head[8:12].decode()
    if head[:2] == b"BM" and len(head) > 14 and head[6:10] == b"\0\0\0\0":
        return "BMP image"
    # Unity SerializedFile (format >= 22): big-endian version at 8, "metadata
    # size" zero and the 2022.x version string a little later.
    if len(head) >= 64 and re.search(rb"20\d\d\.\d+\.\d+[abfp]\d+\0", head[:80]):
        return "Unity SerializedFile"
    if head[:2] == b"MZ" or head[:4] == b"\x7fELF":
        return "executable"
    return None

def allowed_large(path):
    return any(fnmatch.fnmatch(path, g) for g in ALLOW_LARGE)

def check(path, size, head, in_archive, rel):
    why = []
    if BAD_NAME.search(path):
        why.append("game file name")
    exe_ok = in_archive and rel in ARCHIVE_BINARIES
    if BAD_EXT.search(path) and not exe_ok:
        why.append("file type")
    s = sniff(head)
    if s and not (s == "executable" and exe_ok):
        why.append(s)
    if path.endswith(".cs") or (not in_archive and DECOMPILED.search(head)):
        why.append("C# / decompiled code")
    if size > LIMIT and not exe_ok and not allowed_large(rel):
        why.append(f"large file ({size // 1024} KB, not allowlisted)")
    return why

bad = 0
checked = 0
def report(name, why):
    global bad
    bad += 1
    print(f"BAD {name}: {', '.join(why)}")

if mode in ("tracked", "worktree"):
    if mode == "tracked":
        paths = [p for p in open(args[0], "rb").read().decode().split("\0") if p]
    else:
        ignored = {".git"}
        if os.path.exists(".gitignore"):
            for line in open(".gitignore"):
                line = line.strip()
                if line.startswith("/") and not any(c in line for c in "*?["):
                    ignored.add(line.strip("/"))
        paths = []
        for dp, dn, fn in os.walk("."):
            rel = os.path.relpath(dp, ".")
            rel = "" if rel == "." else rel + "/"
            dn[:] = sorted(d for d in dn if (rel + d) not in ignored)
            paths += [rel + f for f in sorted(fn) if (rel + f) not in ignored]
    for p in paths:
        if not os.path.isfile(p):
            continue
        with open(p, "rb") as fh:
            head = fh.read(4096)
        checked += 1
        why = check(p, os.path.getsize(p), head, False, p)
        if why:
            report(p, why)
    where = "tracked files" if mode == "tracked" else "files in the tree (minus .gitignore'd dirs)"
else:
    if not args:
        sys.exit("--archives needs at least one file")
    for a in args:
        n0 = checked
        if a.endswith(".zip"):
            z = zipfile.ZipFile(a)
            members = [(i.filename, i.file_size, lambda i=i: z.open(i).read(4096))
                       for i in z.infolist() if not i.is_dir()]
        elif a.endswith((".tar.gz", ".tgz", ".tar")):
            t = tarfile.open(a)
            members = [(m.name, m.size, lambda m=m: t.extractfile(m).read(4096))
                       for m in t.getmembers() if m.isfile()]
        else:
            continue
        for name, size, read in members:
            rel = name.split("/", 1)[1] if "/" in name else name
            checked += 1
            why = check(name, size, read(), True, rel)
            if why:
                report(f"{os.path.basename(a)}:{name}", why)
        print(f"{os.path.basename(a)}: {checked - n0} files")
    where = "archive members"
if bad:
    sys.stdout.flush()
    print(f"check-no-game-data: {bad} problem(s) in {checked} {where}", file=sys.stderr)
    sys.exit(1)
print(f"check-no-game-data: ok ({checked} {where}, nothing from the game)")
PY
